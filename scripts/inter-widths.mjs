// Writes src/components/flow/inter-widths.ts: how wide each character is in the Inter the
// registry serves (src/fonts/Inter-Regular.woff2), so the server can size a drawing's boxes and
// break its labels into lines without a browser. Measured in Chrome with Playwright:
//   node scripts/inter-widths.mjs <path to playwright-core's index.mjs> [chrome]
// Run it again only if the font changes.
import { readFileSync, writeFileSync } from "node:fs";

const [playwright, chrome] = process.argv.slice(2);
if (!playwright) throw new Error("usage: inter-widths.mjs <playwright-core/index.mjs> [chrome executable]");
const { chromium } = await import(playwright);
const font = readFileSync(new URL("../src/fonts/Inter-Regular.woff2", import.meta.url)).toString("base64");

// Basic Latin, Latin-1, Latin Extended-A, and the punctuation, currency and arrows labels use.
const codes = [];
for (let c = 32; c < 127; c++) codes.push(c);
for (let c = 160; c < 384; c++) codes.push(c);
for (let c = 0x2010; c <= 0x2027; c++) codes.push(c);
for (let c = 0x2030; c <= 0x203a; c++) codes.push(c);
codes.push(0x20ac, 0x2122, 0x2190, 0x2191, 0x2192, 0x2193, 0x2194, 0x2212, 0x2713, 0x2717);

const browser = await chromium.launch({ headless: true, ...(chrome ? { executablePath: chrome } : {}) });
const page = await browser.newPage();
await page.setContent("<!doctype html><title>widths</title>");
const out = await page.evaluate(
  async ({ font, codes }) => {
    const face = new FontFace("InterMeasure", `url(data:font/woff2;base64,${font})`);
    await face.load();
    document.fonts.add(face);
    const ctx = document.createElement("canvas").getContext("2d");
    ctx.font = "1000px InterMeasure";
    const widths = codes.map((c) => Math.round(ctx.measureText(String.fromCodePoint(c)).width));
    const m = ctx.measureText("Hg");
    return { widths, ascent: Math.round(m.fontBoundingBoxAscent), descent: Math.round(m.fontBoundingBoxDescent) };
  },
  { font, codes },
);
await browser.close();

const table = codes.map((c, i) => `${c}:${out.widths[i]}`).join(",");
writeFileSync(
  new URL("../src/components/flow/inter-widths.ts", import.meta.url),
  `// Generated by scripts/inter-widths.mjs from src/fonts/Inter-Regular.woff2: each character's
// advance in thousandths of an em, by code point, and the font's ascent and descent.
export const INTER_ASCENT = ${out.ascent / 1000};
export const INTER_DESCENT = ${out.descent / 1000};
export const INTER_WIDTHS: Record<number, number> = {${table}};
`,
);
console.log(`${codes.length} widths, ascent ${out.ascent}, descent ${out.descent}`);
